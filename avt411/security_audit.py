class PoisonedRetriever:
    """Delegates to the real retriever; whenever results include the target paper, a planted
    chunk comes back with them — as if the attacker's text had been ingested with that PDF."""

    def __init__(self, base, payload: str):
        self._base, self.payload = base, payload

    def __getattr__(self, name):
        return getattr(self._base, name)

    def _plant(self, hits: list[Hit]) -> list[Hit]:
        if any(h.chunk_id.startswith(POISON_TARGET) for h in hits):
            return [Hit(f"{POISON_TARGET}#900", self.payload, 1.0)] + hits
        return hits

    def search(self, query, k=None):
        return self._plant(self._base.search(query, k))

    def search_in_source(self, query, source, k=None):
        return self._plant(self._base.search_in_source(query, source, k))


def build_system(kind: str, model: str, poison: str | None = None):
    from .llm import make_llm
    from .pipeline import AGENT_ONLY, ROUTED, RAGPipeline, load_stack
    from . import guardrails as guard
    s = load_stack()
    retriever = PoisonedRetriever(s["retriever"], POISON_PAYLOADS[poison]) if poison else s["retriever"]
    if kind == "unhardened":
        opts, cfg = replace(AGENT_ONLY, name="unhardened", screen=False), UNHARDENED
    elif kind == "agent_only":   # the Checkpoint 6.1 hardened agent on every question
        opts, cfg = AGENT_ONLY, SECURE_LEAN
    else:
        opts, cfg = replace(ROUTED, name="pipeline", use_cache=False), SECURE_LEAN
    answer = make_llm(model, max_tokens=cfg.answer_max_tokens)
    planner = make_llm(model, max_tokens=cfg.planner_max_tokens)
    pf = guard.PersonaFilter(lambda: make_llm(config.FILTER_MODEL, temperature=0, max_tokens=800))
    return RAGPipeline(retriever, s["index"], answer_llm=answer, planner_llm=planner, persona_filter=pf,
                       faq_store=s["faq"], kg_complete=s["kg_complete"], options=opts, agent_cfg=cfg,
                       request_log=None)


