def run_attack(kind: str, model: str, attack: Attack, judge: Judge) -> dict:
    from .pipeline import Session
    session = Session(build_system(kind, model, attack.poison))
    turns = []
    t0 = time.perf_counter()
    for msg in attack.turns:
        with metered() as m:
            try:
                res = session.send(msg)
                rec = {"answer": res.answer, "trace": res.trace, "events": res.events, "blocked": res.blocked,
                       "route": res.route}
            except Exception as e:  # one provider error must not abort the suite
                rec = {"answer": f"[error] {type(e).__name__}: {e}", "trace": [], "events": [], "blocked": False,
                       "route": "error"}
        tot = m.totals()
        turns.append({"user": msg, **rec, "calls": tot["calls"], "input": tot["input"], "output": tot["output"],
                      "cost": tot["cost"]})
    try:
        outcome, note = attack.detect(turns, judge)
    except Exception as e:
        outcome, note = "ERROR", f"detector error: {e}"
    return {"model": model, "agent": kind, "attack": attack.key, "title": attack.title, "risk": attack.risk,
            "surface": attack.surface, "outcome": outcome, "note": note, "turns": len(turns),
            "routes": ",".join(t["route"] for t in turns), "blocked_turns": sum(t["blocked"] for t in turns),
            "llm_calls": sum(t["calls"] for t in turns), "input_tokens": sum(t["input"] for t in turns),
            "output_tokens": sum(t["output"] for t in turns), "cost_usd": round(sum(t["cost"] for t in turns), 6),
            "latency_s": round(time.perf_counter() - t0, 1), "transcript": turns}


def audit(models: list[str], agents: list[str], keys: list[str] | None, workers: int = 6):
    for m in models:
        config.assert_model_allowed(m)
    attacks = [a for a in ATTACKS if not keys or a.key in keys]
    judge = Judge()
    jobs = [(k, m, a) for m in models for a in attacks for k in agents]
    print(f"Security audit: {len(attacks)} scenario(s) x {len(models)} model(s) x {len(agents)} system(s) = {len(jobs)} sessions")
    done, lock = [0], threading.Lock()

    def work(job):
        row = run_attack(*job, judge)
        with lock:
            done[0] += 1
            print(f"  [{done[0]:3d}/{len(jobs)}] {row['outcome']:7s} {row['agent']:10s} {row['model']:20s} "
                  f"{row['attack']:24s} {row['note'][:80]}")
        return row

    with ThreadPoolExecutor(max_workers=workers) as ex:
        rows = list(ex.map(work, jobs))
    out = config.OUTPUT_DIR / "security"
    out.mkdir(parents=True, exist_ok=True)
    stem = out / f"audit_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    stem.with_suffix(".json").write_text(json.dumps(rows, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    with stem.with_suffix(".csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=[k for k in rows[0] if k != "transcript"])
        w.writeheader()
        for r in rows:
            w.writerow({k: v for k, v in r.items() if k != "transcript"})
    with open(str(stem) + "_transcripts.log", "w", encoding="utf-8") as fh:
        for r in sorted(rows, key=lambda r: (r["attack"], r["model"], r["agent"])):
            fh.write(f"{'#' * 100}\n### {r['attack']} | {r['agent']} | {r['model']} -> {r['outcome']}: {r['note']}\n"
                     f"### calls={r['llm_calls']} in={r['input_tokens']:,} cost=${r['cost_usd']:.4f} latency={r['latency_s']}s\n")
            for i, t in enumerate(r["transcript"], 1):
                user = t["user"] if len(t["user"]) < 1200 else t["user"][:600] + f" …[{len(t['user']):,} chars]"
                fh.write(f"\n  [turn {i}] USER: {user}\n  route: {t['route']}\n")
                for s in t["trace"]:
                    fh.write(f"      {s.get('step')}. {str(s.get('action'))[:200]}  -> {str(s.get('outcome'))[:160]}\n")
                if t["events"]:
                    fh.write(f"      events: {t['events']}\n")
                fh.write(f"  [turn {i}] SYSTEM: {t['answer']}\n")
            fh.write("\n")
    md = summarize(rows, models, agents, attacks)
    stem.with_suffix(".md").write_text(md, encoding="utf-8")
    print("\n" + md + f"\nResults: {stem.with_suffix('.csv')}")
    return stem


def summarize(rows, models, agents, attacks) -> str:
    sym = {"PASS": "held", "PARTIAL": "partial", "FAIL": "FAIL", "ERROR": "error"}
    cols = [(m, a) for m in models for a in agents]
    by = {(r["attack"], r["model"], r["agent"]): r for r in rows}
    lines = ["## Security audit — outcome matrix", "",
             "| Scenario | Risk class | " + " | ".join(f"{a} · {m.split('/')[-1]}" for m, a in cols) + " |",
             "|" + "---|" * (len(cols) + 2)]
    for at in attacks:
        lines.append(f"| {at.key} | {at.risk} | " + " | ".join(sym.get(by[(at.key, m, a)]["outcome"], "?")
                                                              if (at.key, m, a) in by else "—" for m, a in cols) + " |")
    lines += ["", "| System · model | attacks held | controls OK | LLM calls (suite) | $ (suite) | mean latency/session |",
              "|---|---|---|---|---|---|"]
    for m, a in cols:
        rs = [r for r in rows if r["model"] == m and r["agent"] == a]
        att = [r for r in rs if not r["attack"].startswith("X_")]
        ctl = [r for r in rs if r["attack"].startswith("X_")]
        lines.append(f"| {a} · {m} | {sum(r['outcome'] == 'PASS' for r in att)}/{len(att)} "
                     f"({sum(r['outcome'] == 'PARTIAL' for r in att)} partial) | {sum(r['outcome'] == 'PASS' for r in ctl)}/{len(ctl)} | "
                     f"{sum(r['llm_calls'] for r in rs)} | ${sum(r['cost_usd'] for r in rs):.3f} | "
                     f"{statistics.mean(r['latency_s'] for r in rs):.1f}s |")
    lines += ["", "Notes per cell:", ""]
    lines += [f"- **{r['attack']}** · {r['agent']} · {r['model']}: {r['outcome']} — {r['note']} (routes: {r['routes']})"
              for r in sorted(rows, key=lambda r: (r["attack"], r["model"], r["agent"]))]
    return "\n".join(lines) + "\n"
